"""Audit the v0.9 illustration runs with the run checks of the standard art tool (tools/art_gen/artgen.py).

The 51 illustrations were generated by tools/art_v09/generate.py before the standard pipeline (ART-PIPELINE-2)
existed. That pipeline found that Codex can silently drop reference images attached with -i. This script replays
its checks on each run's Codex session log: did the image tool receive the two reference images (by SHA-256), was
the prompt the composed one, was a transparent background requested. It reads only the session logs of these runs
(found by the session id each run printed) and never touches Codex credentials.

    python tools/art_v09/audit_runs.py --logs artifacts/cache/v09/art-logs [--extra C54=<log>] [--write]

--write adds a `runCheck` block to every record.json and writes evidence/v09/art/run-audit.json.
"""
import argparse
import hashlib
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "art_gen"))
import artgen  # noqa: E402

PLAN = ROOT / "tools/art_v09/prompts.json"
OUT = ROOT / "ArtSource/Art09/Illustrations"
EVIDENCE = ROOT / "evidence/v09/art/run-audit.json"


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--logs", required=True)
    parser.add_argument("--extra", action="append", default=[], help="ID=path of a run log kept elsewhere")
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    plan = json.loads(PLAN.read_text(encoding="utf-8"))
    expected = [{"path": str(ROOT / r["path"]), "sha256": sha(ROOT / r["path"])} for r in plan["references"]]
    extra = dict(item.split("=", 1) for item in args.extra)
    home = Path(os.environ.get("CODEX_HOME") or Path.home() / ".codex")
    rows = []
    for entry in plan["entries"]:
        folder = OUT / entry["id"]
        log = Path(extra.get(entry["id"]) or Path(args.logs) / f"{entry['id']}.log")
        row = {"id": entry["id"], "name": entry["name"], "status": "UNVERIFIED", "problems": [], "modelInputImages": None, "threadId": None}
        rows.append(row)
        if not log.exists():
            row["problems"].append("no run log kept")
            continue
        match = re.search(r"session id:\s*([0-9a-f-]{36})", log.read_text(encoding="utf-8", errors="replace"))
        if not match:
            row["problems"].append("run log has no session id")
            continue
        row["threadId"] = match.group(1)
        rollout = artgen.find_rollout(home, row["threadId"])
        if rollout is None:
            row["problems"].append("Codex session log not found")
            continue
        prompt = (folder / "prompt.txt").read_text(encoding="utf-8").rstrip("\n")
        result = artgen.check_run(artgen.parse_rollout(rollout), expected, prompt, True)
        inputs = result["checks"].get("modelInputImages")
        row["modelInputImages"] = None if inputs is None else len(inputs)
        row["problems"] = result["problems"]
        row["checks"] = {k: v for k, v in result["checks"].items() if k != "modelInputImages"}
        row["status"] = "VALID" if not result["problems"] else "INVALID_RUN"
    summary = {s: sum(r["status"] == s for r in rows) for s in ("VALID", "INVALID_RUN", "UNVERIFIED")}
    no_refs = [r["id"] for r in rows if any("referenced_image_paths" in p or "lists no inputImages" in p or "differ from the pinned" in p for p in r["problems"])]
    print(json.dumps(summary), "runs without verified references:", ",".join(no_refs))
    for r in rows:
        if r["status"] != "VALID":
            print(r["id"], r["status"], "; ".join(r["problems"]))
    if args.write:
        for r in rows:
            record_path = OUT / r["id"] / "record.json"
            record = json.loads(record_path.read_text(encoding="utf-8"))
            record["runCheck"] = {"tool": "tools/art_gen/artgen.py check_run via tools/art_v09/audit_runs.py", "status": r["status"],
                                  "modelInputImages": r["modelInputImages"], "problems": r["problems"], "threadId": r["threadId"]}
            if r["status"] != "VALID":
                record["tool"] = "Codex CLI built-in image_gen, one call; two reference images were attached to the request, see runCheck for what the image model actually received"
            record_path.write_text(json.dumps(record, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        EVIDENCE.parent.mkdir(parents=True, exist_ok=True)
        EVIDENCE.write_text(json.dumps({"schema": "v09-art-run-audit-1", "summary": summary, "withoutVerifiedReferences": no_refs, "runs": rows},
                                       ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
